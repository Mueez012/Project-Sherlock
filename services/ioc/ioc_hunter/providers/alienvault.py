def requests_for(ioc: IOC, method: MethodSpec, api_key="") -> list[tuple[str, FetchRequest]]:
    value = quote(ioc.value, safe="")
    op = method.operation
    kind = {"ipv4": "IPv4", "ipv6": "IPv6", "url": "url"}.get(ioc.type, ioc.type)
    api_kind = "URL" if ioc.type == "url" else kind
    section = {"dns": "passive_dns", "urls": "url_list", "geo": "geo", "url_details": "general"}[op]
    endpoint = f"/api/v1/indicators/{api_kind}/{value}/{section}"
    # OTX's own report links retain colons (including the URL scheme), while
    # encoding slashes/query delimiters inside the indicator path parameter.
    ui_value = quote(ioc.value, safe=":")
    ui_kind = "ip" if ioc.type == "ipv6" else kind
    ui = f"https://otx.alienvault.com/indicator/{ui_kind}/{ui_value}"
    labels = {"dns": ("Passive DNS",), "urls": ("URLs",)}.get(op, ())
    # The paper's indicator page is primary. These are responses generated by
    # that page, not direct unauthenticated calls to a private API.
    website_endpoint = f"/otxapi/indicators/{kind}/{section}/{value}"
    website_paths = (website_endpoint,)
    if ioc.type == "url":
        # Observed general-report request encodes the GUI parameter again.
        # Enumerate this exact variant; do not recursively decode arbitrary URLs.
        website_paths += (f"/otxapi/indicators/{kind}/{section}/{quote(ui_value, safe='')}",)
    selector = {"dns": "#passive" if ioc.type in {"ipv4", "ipv6"} else "#passive_dns",
                "urls": "#url_list"}.get(op, "")
    result = [("browser", FetchRequest(source, ui, op, website_paths, page_labels=labels,
                                      bootstrap_paths=("/otxapi/env",), result_selector=selector,
                                      identity_type=ioc.type,
                                      next_selector=(selector + " .page-change.increment") if op == "urls" else "",
                                      page_errors=(("Page not found.", "not_found"),)))]
    if api_key:
        result.append(("http", FetchRequest(source, "https://otx.alienvault.com" + endpoint,
                                           op, headers={"X-OTX-API-KEY": api_key})))
    return result


def parse_document(ioc: IOC, method: MethodSpec, document: Document) -> ParsedPage:
    builder = ObservationBuilder(ioc, method, document)
    if document.format != "json":
        return parse_html(builder, section_id={"dns": "passive" if ioc.type in {"ipv4", "ipv6"} else "passive_dns",
                                             "urls": "url_list"}.get(method.operation))
    data = read_json(document)
    if method.operation == "dns":
        dns_rows(builder, data.get("passive_dns"), "$.passive_dns")
    elif method.operation == "urls":
        url_rows(builder, data.get("url_list"), "$.url_list")
    elif method.operation == "geo":
        if not any(key in data for key in ("country_code", "country", "country_name", "city", "asn", "latitude")):
            from ..transport.models import LookupError
            raise LookupError("parse_error", "Missing geographic response fields")
        locator = "$.country_code" if "country_code" in data else "$.country"
        country_record(builder, data.get("ip", ioc.value), data, locator)
    else:
        url_details(builder, data, "$.url" if "url" in data else "$.indicator")
    return finish_json(builder, data)
