"""Independent evidence/ontology checks. Never scores expansion or mutates a graph.

Evidence is emitted by trusted provider parsers, not generated by an LLM.
Both retrieval direction and field semantics are checked here. An ontology match
alone is insufficient. Temporal and TTP edges belong to their own pipelines.
"""
from dataclasses import dataclass, field
from urllib.parse import urlsplit
from .models import IOC, identity, normalize
from .method_spec import MethodSpec
from .evidence import Evidence
from .ontology import allows_ioc_edge, relationship

@dataclass(frozen=True)
class ValidationResult:
    accepted: bool
    reason: str
    ontology_label: str = ""
    evidence_id: str = ""
    message: str = ""
    details: dict = field(default_factory=dict)


REJECTION_MESSAGES = {
    "method_type_mismatch": "The input or output type does not match the selected method.",
    "outside_ontology": "The ontology does not allow this relationship.",
    "query_echo": "The result repeats the input IOC and would not create a connection.",
    "method_evidence_mismatch": "The evidence source or operation does not match this implemented method.",
    "wrong_query": "This evidence was collected for a different input IOC.",
    "missing_provenance": "The result lacks a source excerpt, locator or response digest.",
    "relationship_not_supported_by_fields": "The provider fields do not support these exact relationship endpoints.",
    "invalid_evidence_fields": "Required evidence fields are missing or malformed.",
}


def validate_edge(input_ioc: IOC, output_ioc: IOC, method: MethodSpec, evidence: Evidence) -> ValidationResult:
    def reject(reason, message="", **details):
        return ValidationResult(False, reason, evidence_id=evidence.id,
                                message=message or REJECTION_MESSAGES.get(reason, reason),
                                details=details)
    try:
        left, right = identity(input_ioc), identity(output_ioc)
        if left[0] != method.input_type or right[0] != method.output_type:
            return reject("method_type_mismatch")
        if not allows_ioc_edge(left[0], right[0]):
            return reject("outside_ontology")
        if left == right:
            return reject("query_echo")
        if not method.implemented or evidence.source != method.source or evidence.operation != method.operation:
            return reject("method_evidence_mismatch")
        if identity(IOC(evidence.query_value, evidence.query_type)) != left:
            return reject("wrong_query")
        if not evidence.excerpt or not evidence.locator or not evidence.response_sha256:
            return reject("missing_provenance")
        facts = evidence.facts
        supported = False
        if evidence.fact_type == "dns_record" and method.operation == "dns":
            domain = ("domain", normalize("domain", facts["domain"]))
            address = facts["ip"]
            kind = "ipv6" if ":" in address else "ipv4"
            ip = (kind, normalize(kind, address))
            expected_domain = left if left[0] == "domain" else right
            expected_ip = right if left[0] == "domain" else left
            if domain != expected_domain:
                return reject("dns_domain_mismatch",
                              f"Expected DNS evidence for {expected_domain[1]}, but this record belongs to {domain[1]}.",
                              expected_domain=expected_domain[1], observed_domain=domain[1])
            if ip != expected_ip:
                return reject("dns_ip_mismatch",
                              f"Expected DNS evidence for {expected_ip[1]}, but this record names {ip[1]}.",
                              expected_ip=expected_ip[1], observed_ip=ip[1])
            expected_record_type = "AAAA" if kind == "ipv6" else "A"
            if facts["record_type"].upper() != expected_record_type:
                return reject("dns_record_type_mismatch",
                              f"An {expected_record_type} record is required for this IP type.",
                              expected_record_type=expected_record_type,
                              observed_record_type=facts["record_type"])
            supported = ({left, right} == {domain, ip}
                         and facts["record_type"].upper() == ("AAAA" if kind == "ipv6" else "A"))
        elif evidence.fact_type == "url_host" and method.operation in {"urls", "url_details"}:
            url = normalize("url", facts["url"])
            domain = normalize("domain", urlsplit(url).hostname or "")
            supported = {left, right} == {("url", url), ("domain", domain)}
        elif evidence.fact_type == "ip_country" and method.operation == "geo":
            ip = normalize(left[0], facts["ip"])
            country = normalize("geo_location", facts["country"])
            supported = left == (left[0], ip) and right == ("geo_location", country)
        elif evidence.fact_type == "url_link" and method.operation == "url_details":
            supported = (left == ("url", normalize("url", facts["from_url"]))
                         and right == ("url", normalize("url", facts["to_url"]))
                         and facts["kind"] in {"redirect", "outgoing_link"})
        if not supported:
            return reject("relationship_not_supported_by_fields")
        return ValidationResult(True, "supported", relationship(left[0], right[0]).label,
                                evidence.id, "Provider fields support this relationship.")
    except (ValueError, KeyError, TypeError, AttributeError):
        return reject("invalid_evidence_fields")


def undirected_edge_key(left: IOC, right: IOC, method_id: str) -> tuple:
    """Optional identity helper for the future algorithm, not edge insertion."""
    return (*sorted((identity(left), identity(right))), method_id)
